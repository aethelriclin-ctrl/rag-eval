"""上下文组装 —— 把检索到的块拼成提示词里的一段资料。

📌 说明：这个文件以前还包含"余弦相似度检索"，但改用 BM25 之后，
   检索逻辑搬到了 rag/bm25.py，余弦相似度留给未来的向量检索实现。
   所以这里现在只负责一件小事：**把 hits 拼成一段文本**。

⚠️ 顺手清理：原来这里有 `import numpy as np`，是给余弦相似度用的。
   BM25 不需要 numpy，所以删掉了 —— 少一个依赖，少一个装不上的理由。
   （教训：换实现时要顺手清掉不再需要的依赖，否则它会一直挡住后来的人。）
"""


def build_context(hits):
    """把检索到的块拼成一段文本，供提示词使用。

    为什么要标来源和编号：
        1. 让模型知道自己引用的是哪一段（第 2 层要测"引用准确性"）
        2. 出问题时我能回溯 —— 这是项目 1 养成的习惯
    """
    parts = []
    for i, h in enumerate(hits, 1):
        parts.append(
            f"【资料 {i}】（来自 {h['source']}，相关度 {h['score']:.3f}）\n{h['text']}"
        )
    return "\n\n".join(parts)
